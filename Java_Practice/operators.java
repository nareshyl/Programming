class operators{
    public static void main(String args []){
        int a = 10;
        int b = 5;
        int c = a + b;
        System.out.println("Addition: " + c);
        int d = a - b;
        System.out.println("Subtraction: " + d);
        int e = a * b;
        System.out.println("Multiplication: " + e);
        int f = a / b;
        System.out.println("Division: " + f);
        int g = a % b;
        System.out.println("Modulus: " + g);
    }
}