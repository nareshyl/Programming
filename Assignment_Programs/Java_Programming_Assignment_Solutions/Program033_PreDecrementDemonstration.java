// Problem 33: Pre-Decrement Demonstration
import java.util.Scanner;

public class Program033_PreDecrementDemonstration {
    public static void main(String[] args) {
        int n = 5;
        System.out.println("Before = " + n);
        System.out.println("Pre-decrement result = " + (--n));
        System.out.println("After = " + n);
    }
}
