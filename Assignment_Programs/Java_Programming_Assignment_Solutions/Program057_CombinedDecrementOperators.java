// Problem 57: Combined Decrement Operators
import java.util.Scanner;

public class Program057_CombinedDecrementOperators {
    public static void main(String[] args) {
        int a = 5, b = 5;
        System.out.println("--a result = " + (--a) + ", a after = " + a);
        System.out.println("b-- result = " + (b--) + ", b after = " + b);
    }
}
