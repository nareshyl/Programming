// Problem 34: Post-Decrement Demonstration
import java.util.Scanner;

public class Program034_PostDecrementDemonstration {
    public static void main(String[] args) {
        int n = 5;
        System.out.println("Before = " + n);
        System.out.println("Post-decrement result = " + (n--));
        System.out.println("After = " + n);
    }
}
