// Problem 32: Post-Increment Demonstration
import java.util.Scanner;

public class Program032_PostIncrementDemonstration {
    public static void main(String[] args) {
        int n = 5;
        System.out.println("Before = " + n);
        System.out.println("Post-increment result = " + (n++));
        System.out.println("After = " + n);
    }
}
