// Problem 31: Pre-Increment Demonstration
import java.util.Scanner;

public class Program031_PreIncrementDemonstration {
    public static void main(String[] args) {
        int n = 5;
        System.out.println("Before = " + n);
        System.out.println("Pre-increment result = " + (++n));
        System.out.println("After = " + n);
    }
}
